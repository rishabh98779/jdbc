"""Reusable SVG diagram primitives for the Java Concepts Integrated Visual Notes.

Every diagram in the book is generated by this toolkit so that typography, colour
and spacing stay consistent.  Colours mirror the book palette (dark navy + teal).
"""
from __future__ import annotations

import os
from xml.sax.saxutils import escape

# ---------------------------------------------------------------- palette
NAVY = "#0E1B2C"
NAVY_2 = "#16344F"
TEAL = "#2E82AC"
TEAL_LIGHT = "#D9EAF3"
TEAL_MID = "#7ACBE5"
INK = "#1A2A3D"
BODY = "#33465C"
MUTED = "#647589"
BORDER = "#DCE4ED"
PAPER = "#FFFFFF"
CANVAS = "#F2F6FA"

GREEN = "#3F9E7C"
GREEN_L = "#DFF2EA"
AMBER = "#D9962B"
AMBER_L = "#FBEFD6"
ORANGE = "#E07B3C"
ORANGE_L = "#FBE3D3"
RED = "#C8545C"
RED_L = "#F8E0E2"
PURPLE = "#6C5CA8"
PURPLE_L = "#E8E4F5"
SLATE_L = "#EDF2F7"

SANS = "DejaVu Sans, Arial, Helvetica, sans-serif"
MONO = "DejaVu Sans Mono, Courier New, monospace"

SEM = {
    "navy": (NAVY, "#FFFFFF", NAVY),
    "teal": (TEAL_LIGHT, INK, TEAL),
    "green": (GREEN_L, INK, GREEN),
    "amber": (AMBER_L, INK, AMBER),
    "orange": (ORANGE_L, INK, ORANGE),
    "red": (RED_L, INK, RED),
    "purple": (PURPLE_L, INK, PURPLE),
    "slate": (SLATE_L, INK, MUTED),
    "white": (PAPER, INK, BORDER),
    "dark": (NAVY_2, "#FFFFFF", NAVY_2),
}


class Canvas:
    """A very small SVG builder tuned for technical diagrams."""

    def __init__(self, width: int, height: int, background: str = PAPER):
        self.w = width
        self.h = height
        self.bg = background
        self.parts: list[str] = []

    # ------------------------------------------------------------ raw
    def add(self, markup: str) -> "Canvas":
        self.parts.append(markup)
        return self

    # ------------------------------------------------------------ shapes
    def rect(self, x, y, w, h, fill=PAPER, stroke=BORDER, rx=8, sw=1.4,
             dash=None, opacity=None):
        d = f' stroke-dasharray="{dash}"' if dash else ""
        o = f' opacity="{opacity}"' if opacity is not None else ""
        self.parts.append(
            f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="{rx}" '
            f'fill="{fill}" stroke="{stroke}" stroke-width="{sw}"{d}{o}/>')
        return self

    def line(self, x1, y1, x2, y2, stroke=MUTED, sw=1.6, dash=None,
             cap="round", opacity=None):
        d = f' stroke-dasharray="{dash}"' if dash else ""
        o = f' opacity="{opacity}"' if opacity is not None else ""
        self.parts.append(
            f'<line x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}" stroke="{stroke}" '
            f'stroke-width="{sw}" stroke-linecap="{cap}"{d}{o}/>')
        return self

    def poly(self, points, fill=PAPER, stroke=BORDER, sw=1.4, opacity=None):
        pts = " ".join(f"{x},{y}" for x, y in points)
        o = f' opacity="{opacity}"' if opacity is not None else ""
        self.parts.append(
            f'<polygon points="{pts}" fill="{fill}" stroke="{stroke}" '
            f'stroke-width="{sw}"{o}/>')
        return self

    def circle(self, cx, cy, r, fill=PAPER, stroke=BORDER, sw=1.4):
        self.parts.append(
            f'<circle cx="{cx}" cy="{cy}" r="{r}" fill="{fill}" '
            f'stroke="{stroke}" stroke-width="{sw}"/>')
        return self

    def ellipse(self, cx, cy, rx, ry, fill=PAPER, stroke=BORDER, sw=1.4):
        self.parts.append(
            f'<ellipse cx="{cx}" cy="{cy}" rx="{rx}" ry="{ry}" fill="{fill}" '
            f'stroke="{stroke}" stroke-width="{sw}"/>')
        return self

    def path(self, d, fill="none", stroke=INK, sw=1.8, dash=None, opacity=None,
             cap="round"):
        da = f' stroke-dasharray="{dash}"' if dash else ""
        o = f' opacity="{opacity}"' if opacity is not None else ""
        self.parts.append(
            f'<path d="{d}" fill="{fill}" stroke="{stroke}" stroke-width="{sw}" '
            f'stroke-linecap="{cap}" stroke-linejoin="round"{da}{o}/>')
        return self

    # ------------------------------------------------------------ text
    def text(self, x, y, s, size=13, fill=INK, anchor="start", weight="normal",
             font=SANS, italic=False, opacity=None, spacing=None):
        st = f' font-style="italic"' if italic else ""
        o = f' opacity="{opacity}"' if opacity is not None else ""
        ls = f' letter-spacing="{spacing}"' if spacing else ""
        self.parts.append(
            f'<text x="{x}" y="{y}" font-family="{font}" font-size="{size}" '
            f'fill="{fill}" text-anchor="{anchor}" font-weight="{weight}"{st}{o}{ls}>'
            f'{escape(str(s))}</text>')
        return self

    def lines(self, x, y, items, size=13, fill=BODY, anchor="start", lh=None,
              weight="normal", font=SANS):
        lh = lh or size + 4
        for i, item in enumerate(items):
            self.text(x, y + i * lh, item, size=size, fill=fill, anchor=anchor,
                      weight=weight, font=font)
        return self

    def mtext(self, x, y, s, size=12, fill=INK, anchor="start", weight="normal"):
        return self.text(x, y, s, size=size, fill=fill, anchor=anchor,
                         weight=weight, font=MONO)

    # ------------------------------------------------------------ arrows
    def _head(self, x, y, ang, color, size=9.5):
        import math
        a1 = math.radians(ang + 152)
        a2 = math.radians(ang - 152)
        p1 = (x + size * math.cos(a1), y + size * math.sin(a1))
        p2 = (x + size * math.cos(a2), y + size * math.sin(a2))
        self.parts.append(
            f'<polygon points="{x},{y} {p1[0]:.2f},{p1[1]:.2f} '
            f'{p2[0]:.2f},{p2[1]:.2f}" fill="{color}"/>')

    def arrow(self, x1, y1, x2, y2, color=TEAL, sw=1.9, dash=None, head=True,
              head_size=9.5, opacity=None):
        import math
        self.line(x1, y1, x2, y2, stroke=color, sw=sw, dash=dash, opacity=opacity)
        if head:
            ang = math.degrees(math.atan2(y2 - y1, x2 - x1))
            self._head(x2, y2, ang, color, head_size)
        return self

    def elbow(self, x1, y1, x2, y2, color=TEAL, sw=1.9, dash=None, mode="hv",
              head=True, head_size=9.5, r=10):
        """Right-angled connector.  mode hv = horizontal then vertical."""
        import math
        if mode == "hv":
            mx, my = x2, y1
        else:
            mx, my = x1, y2
        self.line(x1, y1, mx, my, stroke=color, sw=sw, dash=dash)
        self.line(mx, my, x2, y2, stroke=color, sw=sw, dash=dash)
        if head:
            if mode == "hv":
                ang = 90 if y2 > my else -90
            else:
                ang = 0 if x2 > mx else 180
            self._head(x2, y2, ang, color, head_size)
        return self

    def curve(self, x1, y1, x2, y2, color=TEAL, sw=1.9, bend=40, dash=None,
              head=True, head_size=9.5):
        import math
        cx = (x1 + x2) / 2 + bend
        cy = (y1 + y2) / 2 - bend
        self.path(f"M {x1} {y1} Q {cx} {cy} {x2} {y2}", stroke=color, sw=sw,
                  dash=dash)
        if head:
            ang = math.degrees(math.atan2(y2 - cy, x2 - cx))
            self._head(x2, y2, ang, color, head_size)
        return self

    def label(self, x, y, s, size=11, fill=MUTED, anchor="middle",
              bg=PAPER, pad=4, weight="normal", font=SANS, italic=False):
        """Text with an opaque plate so it can sit on top of a connector."""
        w = len(str(s)) * size * (0.60 if font == SANS else 0.62) + pad * 2
        if anchor == "middle":
            x0 = x - w / 2
        elif anchor == "end":
            x0 = x - w
        else:
            x0 = x
        self.rect(x0, y - size * 0.95, w, size * 1.5, fill=bg, stroke=bg, rx=3,
                  sw=0)
        self.text(x, y, s, size=size, fill=fill, anchor=anchor, weight=weight,
                  font=font, italic=italic)
        return self

    # ------------------------------------------------------------ composites
    def box(self, x, y, w, h, title=None, sub=None, sem="teal", rx=9,
            title_size=13.5, sub_size=11, title_weight="bold", pad=11,
            center=True, mono_title=False, fill=None, stroke=None, sw=1.5,
            title_fill=None, sub_fill=None, dash=None):
        f, tcol, scol = SEM[sem]
        f = fill or f
        scol = stroke or scol
        self.rect(x, y, w, h, fill=f, stroke=scol, rx=rx, sw=sw, dash=dash)
        if title is None:
            return self
        cx = x + w / 2 if center else x + pad
        anchor = "middle" if center else "start"
        ty = y + pad + title_size * 0.85 if not sub else y + pad + title_size * 0.8
        self.text(cx, ty, title, size=title_size, fill=title_fill or tcol,
                  anchor=anchor, weight=title_weight,
                  font=MONO if mono_title else SANS)
        if sub:
            items = sub if isinstance(sub, (list, tuple)) else [sub]
            sy = ty + sub_size + 5
            for i, item in enumerate(items):
                self.text(cx, sy + i * (sub_size + 4), item, size=sub_size,
                          fill=sub_fill or scol, anchor=anchor)
        return self

    def band(self, x, y, w, h, label, sem="navy", size=13, rx=7):
        f, tcol, scol = SEM[sem]
        self.rect(x, y, w, h, fill=f, stroke=scol, rx=rx, sw=1.4)
        self.text(x + w / 2, y + h / 2 + size * 0.36, label, size=size,
                  fill=tcol, anchor="middle", weight="bold", spacing="0.6")
        return self

    def chip(self, x, y, w, h, label, sem="teal", size=11):
        f, tcol, scol = SEM[sem]
        self.rect(x, y, w, h, fill=f, stroke=scol, rx=h / 2, sw=1.3)
        self.text(x + w / 2, y + h / 2 + size * 0.36, label, size=size,
                  fill=tcol, anchor="middle", weight="bold")
        return self

    def title(self, x, y, text, sub=None, size=19, sub_size=12.5, anchor="start"):
        self.text(x, y, text, size=size, fill=NAVY, anchor=anchor,
                  weight="bold")
        if sub:
            self.text(x, y + sub_size + 8, sub, size=sub_size, fill=MUTED,
                      anchor=anchor)
        return self

    def legend(self, x, y, entries, size=11, gap=16, cols=1, col_w=150,
               swatch=11):
        for i, (label, sem) in enumerate(entries):
            r, c = divmod(i, cols)
            bx = x + c * col_w
            by = y + r * (size + 8)
            f, _, s = SEM[sem]
            self.rect(bx, by - swatch + 2, swatch, swatch, fill=f, stroke=s,
                      rx=2.5, sw=1.2)
            self.text(bx + swatch + 7, by, label, size=size, fill=BODY)
        return self

    def note(self, x, y, w, text, sem="amber", size=11.5, pad=9, icon="!"):
        f, tcol, s = SEM[sem]
        lines = text if isinstance(text, (list, tuple)) else [text]
        h = pad * 2 + len(lines) * (size + 4) - 2
        self.rect(x, y, w, h, fill=f, stroke=s, rx=6, sw=1.3)
        self.rect(x, y, 4, h, fill=s, stroke=s, rx=2, sw=0)
        if icon:
            self.circle(x + 17, y + pad + size * 0.5, 7.5, fill=s, stroke=s)
            self.text(x + 17, y + pad + size * 0.5 + 4, icon, size=size - 1,
                      fill=PAPER, anchor="middle", weight="bold")
            tx = x + 31
        else:
            tx = x + pad
        for i, item in enumerate(lines):
            self.text(tx, y + pad + size * 0.8 + i * (size + 4), item,
                      size=size, fill=tcol)
        return h

    def table(self, x, y, col_w, rows, row_h=26, header=True, size=11.5,
              sem="navy", zebra=True, align=None):
        """rows[0] is the header when header=True."""
        total = sum(col_w)
        align = align or ["start"] * len(col_w)
        cy = y
        for r, row in enumerate(rows):
            is_head = header and r == 0
            if is_head:
                f, tcol, s = SEM[sem]
                self.rect(x, cy, total, row_h, fill=f, stroke=s, rx=0, sw=1)
            elif zebra and r % 2 == 0:
                self.rect(x, cy, total, row_h, fill=CANVAS, stroke=CANVAS, rx=0,
                          sw=0)
            cx = x
            for c, cell in enumerate(row):
                txt = str(cell)
                ax = align[c]
                if ax == "start":
                    px, an = cx + 9, "start"
                elif ax == "end":
                    px, an = cx + col_w[c] - 9, "end"
                else:
                    px, an = cx + col_w[c] / 2, "middle"
                self.text(px, cy + row_h / 2 + size * 0.35, txt, size=size,
                          fill=PAPER if is_head else BODY, anchor=an,
                          weight="bold" if is_head else "normal")
                cx += col_w[c]
            self.line(x, cy, x + total, cy, stroke=BORDER, sw=1)
            cy += row_h
        self.line(x, cy, x + total, cy, stroke=BORDER, sw=1)
        for c in range(1, len(col_w)):
            gx = x + sum(col_w[:c])
            self.line(gx, y, gx, cy, stroke=BORDER, sw=1)
        return cy - y

    def frame(self, x, y, w, h, label, sem="slate", size=11, dash="5 4"):
        """Dashed grouping frame with a caption tab."""
        f, tcol, s = SEM[sem]
        self.rect(x, y, w, h, fill="none", stroke=s, rx=8, sw=1.3, dash=dash)
        self.rect(x + 12, y - size * 0.85, len(label) * size * 0.58 + 16,
                  size * 1.7, fill=f, stroke=f, rx=4, sw=0)
        self.text(x + 20, y + size * 0.35, label, size=size, fill=s,
                  weight="bold")
        return self

    # ------------------------------------------------------------ output
    def svg(self) -> str:
        body = "\n".join(self.parts)
        return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{self.w}" '
                f'height="{self.h}" viewBox="0 0 {self.w} {self.h}">'
                f'<rect width="{self.w}" height="{self.h}" fill="{self.bg}"/>'
                f'{body}</svg>')

    def save(self, name: str, svg_dir: str, png_dir: str, scale: float = 2.0):
        import cairosvg
        os.makedirs(svg_dir, exist_ok=True)
        os.makedirs(png_dir, exist_ok=True)
        svg_path = os.path.join(svg_dir, name + ".svg")
        png_path = os.path.join(png_dir, name + ".png")
        data = self.svg()
        with open(svg_path, "w", encoding="utf-8") as fh:
            fh.write(data)
        cairosvg.svg2png(bytestring=data.encode("utf-8"), write_to=png_path,
                         scale=scale, background_color="white")
        return png_path
